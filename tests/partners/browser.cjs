/* global require, process, console, URL, document, innerWidth */
/* eslint-disable @typescript-eslint/no-require-imports -- Standalone Node.js CommonJS test. */
// Local Chromium QA: real auth and persistence, plus one explicitly simulated storage outage.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { parse } = require('dotenv')
const { chromium } = require('playwright')
if (!process.env.PARTNERS_TEST_ENV || !process.env.PARTNERS_TEST_ACCESS || !process.env.PARTNERS_QA_DIR) throw Error('Explicit local test settings required')
const env = parse(fs.readFileSync(process.env.PARTNERS_TEST_ENV))
const db = new URL(env.DATABASE_URL)
if (db.hostname !== '127.0.0.1' || db.port !== '55449' || db.pathname !== '/captacao_preview') throw Error('Isolated test DB only')
const access = JSON.parse(fs.readFileSync(process.env.PARTNERS_TEST_ACCESS, 'utf8').replace(/^\uFEFF/, ''))
const out = path.resolve(process.env.PARTNERS_QA_DIR)
fs.mkdirSync(out, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1365, height: 1000 }, locale: 'pt-BR', timezoneId: 'America/Sao_Paulo' })
    const response = await context.request.post('http://localhost:3116/api/auth/login', { data: { email: access.email, password: access.password } })
    assert.equal(response.status(), 200)
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.setDefaultTimeout(30000)
    await page.goto('http://localhost:3116/corretor/parceiros')
    await page.getByRole('heading', { name: 'Cresça com o EME.' }).waitFor()
    await page.getByText('Conciliação ainda não disponível', { exact: true }).waitFor()
    await page.getByText('Carregando indicações…', { exact: true }).waitFor({ state: 'hidden' })
    assert.equal(await page.getByRole('link', { name: 'Parceiros EME', exact: true }).count(), 1)
    assert.equal(await page.getByLabel('Acessos da mesma equipe').inputValue(), '10')
    await page.getByText('R$ 198,00', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(out, 'partners-desktop.png'), fullPage: true })
    await page.getByRole('tab', { name: 'Simulador', exact: true }).click()
    await page.getByLabel('Modalidade', { exact: true }).selectOption('PRO')
    await page.getByLabel('Assinaturas individuais').fill('1')
    await page.getByText('R$ 25,80', { exact: true }).waitFor()
    await page.getByLabel('Modalidade', { exact: true }).selectOption('SCALE')
    await page.getByText('R$ 77,80', { exact: true }).waitFor()
    await page.getByLabel('Modalidade', { exact: true }).selectOption('AGREEMENT')
    await page.getByText('R$ 23,80', { exact: true }).waitFor()
    await page.getByText('R$ 303,60', { exact: true }).waitFor()
    await page.getByLabel('Assinaturas individuais').fill('0')
    await page.getByRole('alert').filter({ hasText: 'Informe um número inteiro' }).waitFor()
    console.log('PASS simulator individual, team and invalid input')
    await page.getByRole('button', { name: 'Registrar indicação', exact: true }).click()
    let dialog = page.getByRole('dialog')
    const label = 'FIXTURE Parceiro navegador ' + Date.now()
    await dialog.getByLabel('Nome do contato *', { exact: true }).fill(label)
    await dialog.getByLabel('E-mail do contato *', { exact: true }).fill(`browser-${randomUUID()}@example.invalid`)
    await dialog.getByLabel('Modalidade de interesse').selectOption('TEAM')
    await dialog.getByLabel('Acessos da equipe *').fill('10')
    await dialog.getByLabel('Tenho autorização', { exact: false }).check()
    await dialog.getByRole('button', { name: 'Salvar indicação', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('tab', { name: 'Indicações', exact: true }).click()
    await page.getByRole('button', { name: `Acompanhar ${label}`, exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('Etapa', { exact: true }).selectOption('CONTACTED')
    await dialog.getByLabel('Registrar atividade', { exact: false }).fill('FIXTURE Conversa confirmada localmente')
    await dialog.getByLabel('Próxima ação', { exact: true }).fill('Apresentar proposta')
    await dialog.getByRole('button', { name: 'Salvar acompanhamento', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.reload()
    await page.getByRole('tab', { name: 'Indicações', exact: true }).click()
    await page.getByRole('button', { name: `Acompanhar ${label}`, exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByText('Etapa: Contato realizado. FIXTURE Conversa confirmada localmente', { exact: false }).waitFor()
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    console.log('PASS real save, update, reload persistence, history and Escape')
    for (const width of [320, 390, 430]) {
      await page.setViewportSize({ width, height: 844 })
      await page.getByRole('tab', { name: 'Visão geral', exact: true }).click()
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      await page.screenshot({ path: path.join(out, `partners-mobile-${width}.png`), fullPage: true })
      await page.getByRole('tab', { name: 'Planos e parceria', exact: true }).click()
      await page.getByRole('heading', { name: 'Colinha da parceria', exact: true }).waitFor()
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
      const scrollable = page.getByRole('region', { name: 'Tabela de planos', exact: false })
      assert.ok(await scrollable.evaluate(el => el.scrollWidth > el.clientWidth))
      await page.getByRole('button', { name: 'Registrar indicação', exact: true }).click()
      dialog = page.getByRole('dialog')
      await dialog.getByLabel('Tenho autorização', { exact: false }).scrollIntoViewIfNeeded()
      assert.ok(await dialog.getByRole('button', { name: 'Salvar indicação', exact: true }).isVisible())
      const bounds = await dialog.boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1 && bounds.y >= 0 && bounds.y + bounds.height <= 845)
      await page.screenshot({ path: path.join(out, `partners-modal-${width}.png`) })
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
    }
    console.log('PASS 320/390/430 layouts, guide scrolling and modal scrolling')
    await page.setViewportSize({ width: 1365, height: 1000 })
    // Existing routes are only visited. No business actions are performed.
    await page.goto('http://localhost:3116/corretor/captacao')
    await page.getByRole('heading', { name: 'Encontre sua próxima captação.' }).waitFor()
    await page.goto('http://localhost:3116/corretor/conta')
    await page.getByRole('heading', { name: 'Conta', exact: true }).waitFor()
    console.log('PASS existing Captação and Conta routes remain accessible')
    await page.route('**/api/brokers/partners?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'FIXTURE indisponível' }) }))
    await page.goto('http://localhost:3116/corretor/parceiros')
    await page.getByRole('alert').filter({ hasText: 'indicadores estão indisponíveis' }).waitFor()
    await page.getByText('R$ 198,00', { exact: true }).waitFor()
    console.log('PASS simulated storage outage is explicit; simulator still works')
    assert.deepEqual(errors, [])
    console.log('PASS no uncaught browser errors')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
